package report

import (
	"fmt"
	"strings"
)

// Markdown renders the report as plain Markdown: text, lists and tables
// only. The topology is described in words (its components, and how they
// connect); the charts and the picture of the topology are the PDF's.
func (r Report) Markdown() []byte {
	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	p("# %s on \"%s\": %s\n\n", r.ScenarioName, r.Template, r.Verdict)
	p("| | |\n|---|---|\n")
	for _, kv := range r.facts() {
		p("| %s | %s |\n", kv.Key, cell(kv.Value))
	}
	p("\n")
	if r.Error != "" {
		p("**Error:** %s\n\n", r.Error)
	}

	if len(r.Assertions) > 0 {
		p("## Assertions\n\n| | metric | expected | phase | actual | |\n|---|---|---|---|---|---|\n")
		for _, a := range r.Assertions {
			p("| %s | `%s` | %s | %s | %s | %s |\n", okMark(a.Passed), a.Metric, cell(a.Expected), dash(a.Phase), a.Actual, cell(a.Note))
		}
		p("\n")
	}

	p("## Scenario\n\n")
	if r.Description != "" {
		p("%s\n\n", r.Description)
	}
	if r.Reveals != "" {
		p("*What it shows:* %s\n\n", r.Reveals)
	}
	if len(r.Params) > 0 {
		p("| parameter | value |\n|---|---|\n")
		for _, kv := range r.Params {
			p("| `%s` | %s |\n", kv.Key, cell(kv.Value))
		}
		p("\n")
	}

	if len(r.Nodes) > 0 {
		p("## Topology\n\n### Components\n\n")
		for _, n := range r.Nodes {
			p("- **`%s`**: %s, %s, image `%s`, %s\n", n.ID, n.Kind, replicas(n.Replicas), n.Image, n.Limits)
			if n.Measured {
				p("  - peak use: %s%% of a core, %s MB\n", num(n.PeakCPU), num(n.PeakMem))
			}
			if n.Hot != "" {
				p("  - hot config: `%s`\n", n.Hot)
			}
			if n.Cold != "" {
				p("  - cold config: `%s`\n", n.Cold)
			}
		}
		p("\n")
	}
	if len(r.Edges) > 0 {
		p("### Connections\n\n")
		for _, e := range r.Edges {
			p("- %s\n", e.sentence())
		}
		p("\n")
	}

	if len(r.KeyNumbers) > 0 {
		p("## Results\n\n| | |\n|---|---|\n")
		for _, kv := range r.KeyNumbers {
			p("| %s | %s |\n", kv.Key, kv.Value)
		}
		p("\n")
	}
	if len(r.PhaseRows) > 0 {
		p("### Per phase (mean)\n\n")
		table(&b, r.PhaseColumns, r.PhaseRows)
	}

	if len(r.Timeline) > 0 {
		p("## Timeline\n\n| at | what the runner did |\n|---|---|\n")
		for _, e := range r.Timeline {
			p("| %ss | %s |\n", num(e.T), cell(e.Text))
		}
		p("\n")
	}
	if len(r.DataRows) > 0 {
		p("## Data\n\nThe headline series, averaged over steps of the run. (The PDF report draws every series as a chart.)\n\n")
		table(&b, r.DataColumns, r.DataRows)
	}
	if len(r.Summary) > 0 {
		p("## Every summary value\n\n| key | value |\n|---|---|\n")
		for _, kv := range r.Summary {
			p("| `%s` | %s |\n", kv.Key, kv.Value)
		}
		p("\n")
	}
	p("---\n\nGenerated by Symphony from run `%s`.\n", r.RunID)
	return []byte(b.String())
}

// facts are the lines under the title.
func (r Report) facts() []KV {
	out := []KV{{"Run", "`" + r.RunID + "`"}, {"Scenario", "`" + r.Scenario + "` " + r.ScenarioName}, {"Template", r.Template},
		{"Started", r.Started.Format("2006-01-02 15:04:05")}}
	if !r.Ended.IsZero() {
		out = append(out, KV{"Took", r.Ended.Sub(r.Started).Round(1e9).String()})
	}
	passed, total := 0, len(r.Assertions)
	for _, a := range r.Assertions {
		if a.Passed {
			passed++
		}
	}
	verdict := r.Verdict
	if total > 0 {
		verdict += fmt.Sprintf(" (%d of %d assertions hold)", passed, total)
	}
	return append(out, KV{"Verdict", verdict})
}

func table(b *strings.Builder, cols []string, rows [][]string) {
	b.WriteString("| " + strings.Join(cols, " | ") + " |\n|" + strings.Repeat("---|", len(cols)) + "\n")
	for _, row := range rows {
		b.WriteString("| " + strings.Join(row, " | ") + " |\n")
	}
	b.WriteString("\n")
}

// cell makes a value safe inside a table cell.
func cell(s string) string {
	return strings.NewReplacer("|", "\\|", "\n", " ").Replace(s)
}

func dash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}

func okMark(ok bool) string {
	if ok {
		return "ok"
	}
	return "**FAIL**"
}

// peaks prints the edge's worst failure rate and highest rate, "-" for the
// one the run did not record.
func (e EdgeRow) peaks() (fail, rate string) {
	fail, rate = "-", "-"
	if e.Measured {
		fail = num(e.PeakError*100) + "%"
	}
	if e.RateMeasured {
		rate = num(e.PeakRPS) + " req/s"
	}
	return fail, rate
}

func replicas(n int) string {
	if n == 1 {
		return "1 replica"
	}
	return fmt.Sprintf("%d replicas", n)
}

// sentence says how an edge connects its two nodes, with what the run
// measured on it.
func (e EdgeRow) sentence() string {
	var s string
	switch e.Kind {
	case "publishes":
		s = fmt.Sprintf("`%s` publishes `%s` to `%s`", e.From, e.Topic, e.To)
	case "subscribes":
		s = fmt.Sprintf("`%s` delivers `%s` to `%s`", e.From, e.Topic, e.To)
	case "uses":
		s = fmt.Sprintf("`%s` uses `%s`", e.From, e.To)
	default:
		s = fmt.Sprintf("`%s` calls `%s`", e.From, e.To)
	}
	s += fmt.Sprintf(" (edge `%s`", e.ID)
	if e.TimeoutMs > 0 {
		s += fmt.Sprintf(", timeout %d ms", e.TimeoutMs)
	}
	if e.Retries > 0 {
		s += fmt.Sprintf(", %d retries", e.Retries)
	}
	s += ")"
	fail, rate := e.peaks()
	var seen []string
	if e.Measured {
		seen = append(seen, "peak failure rate "+fail)
	}
	if e.RateMeasured {
		seen = append(seen, "peak "+rate)
	}
	if len(seen) > 0 {
		s += ": " + strings.Join(seen, ", ")
	}
	return s
}

// orDefault prints an edge's override, or says the node's default applies.
func orDefault(v int, unit string) string {
	if v == 0 {
		return "default"
	}
	return fmt.Sprintf("%d%s", v, unit)
}
